-- 今後追加される団員にも自動で請求管理行を作る。
create or replace function public.ensure_member_billing_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.member_billing (member_id)
  values (new.id)
  on conflict (member_id) do nothing;
  return new;
end;
$$;

revoke execute on function public.ensure_member_billing_row()
  from public, anon, authenticated, service_role;

drop trigger if exists members_ensure_member_billing on public.members;
create trigger members_ensure_member_billing
after insert on public.members
for each row execute function public.ensure_member_billing_row();

