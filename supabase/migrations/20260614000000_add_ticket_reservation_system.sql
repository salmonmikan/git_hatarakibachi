create table public.ticket_events (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  description text,
  venue text,
  opens_at timestamptz,
  closes_at timestamptz,
  sanity_performance_id text,
  status text not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint ticket_events_status_check
    check (status in ('draft', 'published', 'closed')),
  constraint ticket_events_slug_path_segment_check
    check (slug ~ '^[A-Za-z0-9_-]+$'),
  constraint ticket_events_title_check
    check (nullif(btrim(title), '') is not null),
  constraint ticket_events_time_order_check
    check (closes_at is null or opens_at is null or closes_at >= opens_at),
  constraint ticket_events_published_sanity_check
    check (
      status not in ('published', 'closed')
      or nullif(btrim(sanity_performance_id), '') is not null
    )
);

create table public.ticket_windows (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.ticket_events(id) on delete cascade,
  label text not null,
  starts_at timestamptz,
  capacity integer not null default 0,
  sort_order numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint ticket_windows_capacity_check
    check (capacity >= 0),
  constraint ticket_windows_label_check
    check (nullif(btrim(label), '') is not null)
);

create table public.ticket_reservations (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.ticket_events(id) on delete restrict,
  window_id bigint references public.ticket_windows(id) on delete set null,
  reservation_code text not null unique,
  customer_name text not null,
  customer_email text not null,
  quantity integer not null default 1,
  status text not null default 'reserved',
  note text,
  request_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  cancelled_at timestamptz,
  deleted_at timestamptz,
  constraint ticket_reservations_quantity_check
    check (quantity > 0),
  constraint ticket_reservations_status_check
    check (status in ('reserved', 'cancelled')),
  constraint ticket_reservations_customer_name_length_check
    check (char_length(customer_name) <= 200),
  constraint ticket_reservations_customer_email_length_check
    check (char_length(customer_email) <= 320),
  constraint ticket_reservations_note_length_check
    check (note is null or char_length(note) <= 2000)
);

